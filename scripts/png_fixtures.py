"""Generate deterministic PNG fixtures using Python's independent zlib encoder."""

from pathlib import Path
import struct
import zlib


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def image(depth, width, height, pattern):
    raw = bytearray()
    maximum = (1 << depth) - 1
    for y in range(height):
        row = bytearray((width * depth + 7) // 8)
        for x in range(width):
            if pattern == "gradient":
                gray = x * 255 // max(1, width - 1)
            elif pattern == "detail":
                gray = (x * 17 + y * 31 + (x ^ y) * 7) & 255
            else:
                gray = 255
                if x % 240 < 2 or y % 165 < 2:
                    gray = 0
                elif x % 240 < 190 and 20 < y % 165 < 100:
                    gray = ((x // 12 + y // 9) % 8) * 255 // 7
            sample = (gray * maximum + 127) // 255
            row[x * depth // 8] |= sample << (8 - depth - x * depth % 8)
        raw.append(0)
        raw.extend(row)
    header = struct.pack(">IIBBBBB", width, height, depth, 0, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
            + chunk(b"IDAT", zlib.compress(raw, 6)) + chunk(b"IEND", b""))


def generate(directory, benchmark=False):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    width, height = (1200, 825) if benchmark else (259, 37)
    entries = []
    output = ["// Generated by scripts/png_fixtures.py; do not edit.",
              "#pragma once", "#include <stddef.h>", "#include <stdint.h>",
              "struct PngFixture { const char *name; const uint8_t *data; size_t size; "
              "unsigned width, height, depth; };"]
    for depth in (1, 2, 4, 8):
        for pattern in ("dashboard", "gradient", "detail"):
            name = f"{pattern}_{depth}"
            data = image(depth, width, height, pattern)
            output.append(f"static const uint8_t png_{name}[] = {{")
            for offset in range(0, len(data), 24):
                output.append(",".join(str(value) for value in data[offset:offset + 24]) + ",")
            output.append("};")
            entries.append(f'{{"{name}", png_{name}, sizeof(png_{name}), {width}, {height}, {depth}}}')
            if benchmark:
                (directory / f"{name}.png").write_bytes(data)
    output.append("static const PngFixture pngFixtures[] = {" + ",\n".join(entries) + "};")
    output.append("static const size_t pngFixtureCount = sizeof(pngFixtures) / sizeof(pngFixtures[0]);")
    (directory / "png_fixtures.h").write_text("\n".join(output) + "\n")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory")
    parser.add_argument("--benchmark", action="store_true")
    arguments = parser.parse_args()
    generate(arguments.directory, arguments.benchmark)
